const LANGS = ["ru", "en", "uz"];
const LANG_KEY = "uhdf-lang";

function getLang() {
  const fromUrl = new URLSearchParams(location.search).get("lang");
  if (LANGS.includes(fromUrl)) { localStorage.setItem(LANG_KEY, fromUrl); return fromUrl; }
  const saved = localStorage.getItem(LANG_KEY);
  if (LANGS.includes(saved)) return saved;
  const nav = (navigator.language || "ru").slice(0, 2);
  return LANGS.includes(nav) ? nav : "ru";
}

function t(key, lang = getLang()) {
  return (I18N[lang] && I18N[lang][key]) ?? I18N.ru[key] ?? key;
}

function applyI18n(lang = getLang()) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n, lang); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder, lang); });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria, lang)); });
  document.querySelectorAll(".lang-switch button").forEach(b => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
}

function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  localStorage.setItem(LANG_KEY, lang);
  applyI18n(lang);
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}
